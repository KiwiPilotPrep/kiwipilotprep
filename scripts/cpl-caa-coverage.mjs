/**
 * Does the course actually teach what the CAA syllabus asks for?
 *
 * This is the validation layer, and it is deliberately a separate program from
 * everything a student can see. The syllabus is a checklist held against the
 * finished course; it is not the course's structure, it does not name a single
 * chapter, and nothing it produces is ever written into a lesson.
 *
 * The mapping it reads is the one the curriculum declares — each chapter names
 * the AC61-5 areas it teaches — resolved through the syllabus rows in the
 * database, which are archived and therefore invisible to the reader but still
 * present as the record of what answers what.
 *
 * Writes docs/cms/CPL-CAA-COVERAGE.md. For development and QA only.
 *
 *   node scripts/cpl-caa-coverage.mjs [--subject <slug>]
 */
import fs from "node:fs";
import path from "node:path";
import { PrismaClient } from "@prisma/client";

import { SUBJECTS } from "../content/cpl/index.mjs";

const db = new PrismaClient();
const OUT = "docs/cms";
const COURSE = "cpl-theory";

/**
 * Requirements whose coverage was checked by hand and found to need teaching
 * the deck does not give, with what was added.
 *
 * Recorded here rather than inferred, because "a chapter claims this area" is
 * not the same as "the material answers this requirement". Every entry was
 * decided by reading the requirement against the built lesson.
 */
const FILLED = {
  "18.4.2": "The deck teaches the reciprocal but never uses the CAA's term for it. A key point in “Bearings: True, Magnetic, Compass and Relative” now names the back bearing and gives an example.",
  "18.4.4": "Slide 36 is the only slide on deriving tracks and bearings from a chart and carries nothing but an instruction to the instructor, so it is skipped. “Converting Between Bearing References” now carries authored teaching on meridian convergence, measuring against the mid-leg meridian, using the latitude scale for distance, and the result being true rather than magnetic.",
  "18.12.4": "The deck's cruising level table stops at the transition altitude. “VFR Cruising Levels” now explains that the same magnetic-track split continues above it expressed as flight levels, and points at the AIP as the authority for the published table.",
  "18.28.14": "The deck states that metres and feet cannot be converted on the navigation computer, which is true of the index marks but leaves a required conversion untaught. “Unit Conversions” now gives the multiplication method against 3.28.",
  "18.42.2": "The deck's chart preparation slide covers aerodromes, tracks and ETA marks but not heading-change markings. “Preparing the Chart” now covers 1:60 marks and drift lines and what each is for.",
  "18.46.12": "Latest time of departure appears nowhere in the deck. “Time Terminology” now carries a worked example deriving it from the latest acceptable arrival, the elapsed time and any held margin.",
};

/**
 * Areas that carry no requirement to teach.
 *
 * "Reserved" areas hold a number the CAA has kept for future use and no
 * requirement text at all; 16.38 is marked in the syllabus itself as applying
 * to helicopter candidates only, and this is the aeroplane course. Neither is
 * a gap, and counting them as one would make the audit lie in the direction
 * that flatters nobody.
 */
const NOT_APPLICABLE = {
  reserved: /^reserved$/i,
  helicopterOnly: /helicopter candidates only|helicopter external load/i,
};

/** Requirements that are practical flight-test skills rather than theory. */
const PRACTICAL = {
  "18.6.4": "Measuring to ±1% on a chart is a ruler skill. The method and the caution about which scale to measure from are taught; the accuracy is demonstrated in the air, not on a page.",
  "18.10.6": "Plotting to ±0.5 of a minute is the same: the convention is taught, the precision is practised.",
  "18.46.2": "Deriving a consumption rate from a sample Aircraft Flight Manual needs the manual for the aircraft being flown. The deck supplies rates for the worked example and the method is taught against those.",
};

function line(o, t = "") { o.push(t); }

async function main() {
  const only = process.argv.includes("--subject")
    ? process.argv[process.argv.indexOf("--subject") + 1]
    : null;
  const chosen = only ? SUBJECTS.filter((s) => s.slug === only) : SUBJECTS;

  const out = [];
  line(out, "# CPL Theory — CAA syllabus coverage");
  line(out);
  line(out, "Internal validation only. Generated by `scripts/cpl-caa-coverage.mjs`.");
  line(out, "**Nothing in this file is student-facing.** The CAA syllabus is a checklist held");
  line(out, "against the course, never the course's own structure.");
  line(out);

  let gaps = 0;

  for (const subject of chosen) {
    const row = await db.subject.findFirst({
      where: { slug: subject.slug, course: { slug: COURSE } },
      select: { id: true, title: true },
    });
    if (!row) continue;

    const topics = await db.syllabusTopic.findMany({
      where: { subjectId: row.id },
      orderBy: { displayOrder: "asc" },
      select: {
        code: true, title: true, status: true,
        items: {
          orderBy: { displayOrder: "asc" },
          select: { id: true, code: true, requirement: true },
        },
      },
    });

    // Which chapter claims which area, from the curriculum itself.
    const claims = new Map();
    for (const chapter of subject.chapters) {
      for (const code of chapter.syllabus ?? []) {
        claims.set(code, [...(claims.get(code) ?? []), chapter.title]);
      }
    }

    // And which lessons are actually mapped to each item, from the database.
    const itemIds = topics.flatMap((t) => t.items.map((i) => i.id));
    const maps = await db.lessonSyllabusItem.findMany({
      where: { syllabusItemId: { in: itemIds } },
      select: { syllabusItemId: true, lesson: { select: { title: true, module: { select: { title: true } } } } },
    });
    const byItem = new Map();
    for (const m of maps) {
      byItem.set(m.syllabusItemId, [...(byItem.get(m.syllabusItemId) ?? []), m.lesson]);
    }

    line(out, `## ${row.title}`);
    line(out);
    line(out, `Syllabus rows are **${topics[0]?.status ?? "n/a"}** — invisible to a student, retained as the mapping record.`);
    line(out);
    line(out, "| Requirement | Verdict | Taught in | Note |");
    line(out, "| --- | --- | --- | --- |");

    for (const topic of topics) {
      for (const item of topic.items) {
        const lessons = byItem.get(item.id) ?? [];
        const chapters = [...new Set(lessons.map((l) => l.module.title))];
        const area = item.code.split(".").slice(0, 2).join(".");
        const filled = FILLED[area] ?? FILLED[item.code];
        const practical = PRACTICAL[area] ?? PRACTICAL[item.code];

        const na =
          NOT_APPLICABLE.reserved.test((topic.title ?? "").trim()) ||
          NOT_APPLICABLE.helicopterOnly.test(topic.title ?? "");
        let verdict = "COVERED BY PPT";
        if (na) verdict = "NOT APPLICABLE";
        else if (lessons.length === 0) { verdict = "**NOT COVERED**"; gaps += 1; }
        else if (filled) verdict = "COVERED — gap filled";
        else if (practical) verdict = "COVERED — practical element";

        const req = (item.requirement ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|");
        line(
          out,
          `| \`${item.code}\` ${req.slice(0, 110)}${req.length > 110 ? "…" : ""} | ${verdict} | ${chapters.join("; ") || "—"} | ${(filled ?? practical ?? "").replace(/\|/g, "\\|")} |`,
        );
      }
    }
    line(out);

    // Areas the curriculum claims that the syllabus does not contain, and the
    // reverse. Either is a mapping error rather than a teaching one.
    const known = new Set(topics.map((t) => t.code));
    const unknown = [...claims.keys()].filter((c) => !known.has(c));
    const notApplicable = topics.filter(
      (t) =>
        !claims.has(t.code) &&
        (NOT_APPLICABLE.reserved.test((t.title ?? "").trim()) ||
          NOT_APPLICABLE.helicopterOnly.test(t.title ?? "")),
    );
    const unclaimed = topics
      .filter((t) => !claims.has(t.code) && !notApplicable.includes(t))
      .map((t) => `${t.code} ${t.title}`);
    if (notApplicable.length) {
      line(out, `**Not applicable to this course:** ${notApplicable.map((t) => `${t.code} ${t.title}`).join(", ")}`);
    }
    if (unknown.length) line(out, `**Curriculum claims areas not in the syllabus:** ${unknown.join(", ")}`);
    if (unclaimed.length) { line(out, `**Syllabus areas no chapter claims:** ${unclaimed.join(", ")}`); gaps += unclaimed.length; }
    if (!unknown.length && !unclaimed.length) {
      line(out, `All ${topics.length} syllabus areas are claimed by a chapter, and every area claimed exists in the syllabus.`);
    }
    line(out);

    line(out, "### Teaching added to close a gap");
    line(out);
    for (const [code, note] of Object.entries(FILLED)) line(out, `- **${code}** — ${note}`);
    line(out);
    line(out, "### Requirements with a practical element");
    line(out);
    for (const [code, note] of Object.entries(PRACTICAL)) line(out, `- **${code}** — ${note}`);
    line(out);
  }

  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, "CPL-CAA-COVERAGE.md"), out.join("\n"));
  console.log(`wrote ${OUT}/CPL-CAA-COVERAGE.md`);
  console.log(gaps === 0 ? "every syllabus requirement has teaching behind it" : `${gaps} requirement(s) with no teaching`);

  await db.$disconnect();
  if (gaps) process.exit(1);
}

main().catch(async (e) => { console.error(e); await db.$disconnect(); process.exit(1); });
