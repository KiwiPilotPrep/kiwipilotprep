say("been seeded with placeholder text telling students the real material is uploaded through the");
say("admin console.");
say();
const archived = await db.subject.count({
  where: { course: { slug: { in: ["ppl-flight-test", "cpl-flight-test"] } }, status: "ARCHIVED" },
});
say(`${archived} archived subjects remain on the two courses, left from an earlier attempt that`);
say("modelled the eight modules as subjects. They are empty, archived and unreachable, and are");
say("kept rather than deleted so nothing that once referenced them breaks.");
say();

fs.mkdirSync("docs/cms", { recursive: true });
fs.writeFileSync(OUT, `${lines.join("\n")}\n`);
console.log(`${OUT} — ${lines.length} lines`);
await db.$disconnect();
